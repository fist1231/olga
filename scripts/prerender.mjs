// Runs after `vite build`. Writes one ready-made HTML file per page (so search engines and
// link previews see real content), plus 404.html, sitemap.xml, robots.txt, and .htaccess
// (the settings file Hostinger's web server reads).
import { mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dist = join(root, "dist");
const server = join(root, "dist-ssr");

const { render, metaFor, allPaths, SITE_URL } = await import(pathToFileURL(join(server, "entry-server.js")).href);
const template = await readFile(join(dist, "index.html"), "utf8");

const esc = (v) => String(v).replace(/&/g, "&amp;").replace(/"/g, "&quot;").replace(/</g, "&lt;").replace(/>/g, "&gt;");

function headFor(path) {
  const meta = metaFor(path);
  const tags = meta.tags.map(([tag, attrs, text]) => {
    const a = Object.entries(attrs)
      .map(([k, v]) => ` ${k}="${esc(v)}"`)
      .join("");
    return tag === "script" ? `<script${a} data-seo>${text}</script>` : `<${tag}${a} data-seo />`;
  });
  return `<title>${esc(meta.title)}</title>\n    ${tags.join("\n    ")}`;
}

function page(path) {
  return template
    .replace("<!--seo-head-->", () => headFor(path))
    .replace('<div id="root"></div>', () => `<div id="root">${render(path)}</div>`);
}

// "/" → index.html; every other page goes in pages/: "/shop" → pages/shop.html, "/shop/riga" → pages/shop/riga.html.
// .htaccess maps the clean address to that file. (Keeping them in pages/ means there's never a real "shop"
// folder next to the /shop address, which would make the server add a trailing slash.)
const fileFor = (path) => (path === "/" ? "index.html" : `pages${path}.html`);

if (!template.includes("<!--seo-head-->")) throw new Error("index.html is missing the <!--seo-head--> marker");

for (const path of allPaths) {
  const file = join(dist, fileFor(path));
  await mkdir(dirname(file), { recursive: true });
  await writeFile(file, page(path));
}
await writeFile(join(dist, "404.html"), page("/404"));

const urls = allPaths.map((p) => `  <url><loc>${esc(metaFor(p).canonical)}</loc></url>`);
await writeFile(
  join(dist, "sitemap.xml"),
  `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${urls.join("\n")}\n</urlset>\n`,
);
await writeFile(join(dist, "robots.txt"), `User-agent: *\nAllow: /\n\nSitemap: ${SITE_URL}/sitemap.xml\n`);

await writeFile(join(dist, ".htaccess"), htaccess(new URL(SITE_URL).hostname));

await rm(server, { recursive: true, force: true });
console.log(`Pre-rendered ${allPaths.length} pages + 404 for ${SITE_URL}`);
if (SITE_URL.endsWith(".example")) {
  console.warn("\n⚠️  SITE_URL is still the placeholder. Set the real address in vite.config.js before uploading.\n");
}

// Settings for Hostinger's web server (LiteSpeed, which reads Apache-style .htaccess files).
function htaccess(host) {
  const bare = host.replace(/^www\./, "");
  const hostRe = bare.replace(/\./g, "\\.");
  return String.raw`# Generated by scripts/prerender.mjs on every build. Edit that script, not this file.
Options -MultiViews -Indexes
DirectoryIndex index.html
ErrorDocument 404 /404.html

RewriteEngine On

# One official address: always https, always ${host}.
# (Only touches ${bare} and www.${bare}; Hostinger's temporary preview addresses are left alone.)
RewriteCond %{HTTPS} off [OR]
RewriteCond %{HTTP_HOST} !^${host.replace(/\./g, "\\.")}$ [NC]
RewriteCond %{HTTP_HOST} ^(www\.)?${hostRe}$ [NC]
RewriteRule ^ https://${host}%{REQUEST_URI} [R=301,L]

# Old Squarespace addresses → new pages (keeps Google rankings and old links working).
RewriteRule ^shop/p/([^/]+)/?$ /shop/$1 [R=301,L]
RewriteRule ^about-1/?$ /about [R=301,L]
RewriteRule ^contact-1/?$ /contact [R=301,L]
RewriteRule ^framing-mounting/?$ /framing [R=301,L]
RewriteRule ^news/?$ / [R=301,L]

# Visitors typing /index.html or /pages/x.html get sent to the clean address.
RewriteCond %{THE_REQUEST} \s/+index\.html[\s?]
RewriteRule ^ / [R=301,L]
RewriteCond %{THE_REQUEST} \s/+pages/(\S+?)\.html[\s?]
RewriteRule ^ /%1 [R=301,L]

# Drop a trailing slash: /shop/ → /shop
RewriteCond %{REQUEST_FILENAME} !-d
RewriteRule ^(.+)/$ /$1 [R=301,L]

# Serve each clean address from its pre-built page: /shop/riga → /pages/shop/riga.html
RewriteCond %{DOCUMENT_ROOT}/pages/$1.html -f
RewriteRule ^(.+)$ /pages/$1.html [L]

# Browser caching: build files have unique names, so they can be kept for a year.
<IfModule mod_headers.c>
  <FilesMatch "\.(js|css|woff2?)$">
    Header set Cache-Control "public, max-age=31536000, immutable"
  </FilesMatch>
  <FilesMatch "\.(webp|png|jpe?g|svg|ico)$">
    Header set Cache-Control "public, max-age=2592000"
  </FilesMatch>
  <FilesMatch "\.(html|xml|txt)$">
    Header set Cache-Control "no-cache"
  </FilesMatch>
</IfModule>
`;
}
